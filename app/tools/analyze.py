def extract_sostav(text):
    if not isinstance(text, str) or not text: return ''
    m = re.search(r'Состав\s*[:：]\s*', text, re.IGNORECASE)
    if not m: return ''
    s = text[m.end():]
    return re.split(r'(Условия и сроки хранения|Условия хранения|Срок годности|Пищевая ценность|Пищевая и энергетическая|Энергетическая ценность|Дата изготовления)', s)[0].strip(' .;:')

def split_ingredients(s):
    if not s: return []
    parts, depth, cur = [], 0, ''
    for ch in s:
        if ch in '([': depth += 1
        elif ch in ')]': depth = max(0, depth-1)
        if ch in ',;' and depth == 0: parts.append(cur); cur = ''
        else: cur += ch
    if cur.strip(): parts.append(cur)
    return [re.sub(r'\s+',' ',p).strip(' .') for p in parts if len(p.strip())>1]

