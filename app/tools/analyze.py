# кириллические буквы-двойники в суффиксах Е-кодов: «Е160а» -> E160a, «Е500іі» -> E500ii
CYR2LAT = str.maketrans({'а': 'a', 'б': 'b', 'с': 'c', 'д': 'd', 'е': 'e', 'і': 'i', 'в': 'b'})

def find_additives(ingredients):
    found = []
    for ing in ingredients:
        low = ing.lower()
        specific_cls = set()
        for m in re.finditer(r'(?<![а-яёa-z])[еe]\s?\d{3,4}[a-zа-я]?(?:[iі]{1,3})?(?![а-яёa-z\d])', low):
            raw = re.sub(r'\s+', '', m.group(0)).translate(CYR2LAT)
            code = 'E' + raw[1:]
            # «Е500ii»/«Е160а» -> полный код, иначе обрезаем буквенный/римский суффикс
            while code and code not in E_DB and not code[-1].isdigit():
                code = code[:-1]
            if code and code in E_DB:
                lvl, nm, cls, com = E_DB[code]
                found.append({'code':code,'name':nm,'cls':cls,'lvl':lvl,'note':com})
                specific_cls.add(cls)
        for pat, code in NAME2CODE:
            if code in E_DB and re.search(pat, low):
                lvl, nm, cls, com = E_DB[code]
                found.append({'code':code,'name':nm,'cls':cls,'lvl':lvl,'note':com})
                specific_cls.add(cls)
        for pat, lvl, nm, cls, com in NAMED_DB:
            if re.search(pat, low):
                if nm in GENERIC_NAMES and cls in specific_cls:
                    continue
                found.append({'code':'','name':nm,'cls':cls,'lvl':lvl,'note':com})
        # неуточнённая «пищевая добавка» (без слова «комплексная»)
        if re.search(r'пищевая\s+добавк', low) and 'комплексн' not in low:
            found.append({'code':'','name':'Пищевая добавка (неуточнённая)','cls':'комплексная добавка','lvl':2,'note':'Вид добавки не раскрыт'})
    seen, uniq = set(), []
    for f in found:
        if f['name'] not in seen: seen.add(f['name']); uniq.append(f)
    return uniq

