KEEP_NODATA = {'edostavka': True, 'green': True, 'av': True, 'mak': True}

products, skipped_junk, skipped_nodata = [], 0, 0
green_unmatched = Counter()
for fpath, shop in FILES:
    raw = json.load(open(fpath))
    for row in raw:
        name = row.get('name', '')
        if shop == 'green':
            cat = green_cat(row.get('category', ''), name)
            if cat is None:
                if (row.get('composition') or '').strip():
                    green_unmatched[row.get('category', '').split('/')[0]] += 1
                continue
        elif shop == 'av':
            cat = av_cat(row.get('category', ''), name)
            if cat is None:
                continue
        elif shop == 'mak':
            cat = mak_cat(row.get('category', ''), name)
            if cat is None:
                continue
        else:
            cat = row.get('category', '')
            if cat == 'Детские товары':
                if not BABY_RE.search(name): continue
                cat = 'Детское питание'
            cat = CAT_MAP.get(cat, cat)
            if cat not in FOOD_CATS: continue
        comp = row.get('composition', '') or ''
        label = row.get('composition_label', '') or ''
        if JUNK_COMP.search(comp):
            if label:
                comp = 'Состав: ' + label
                label = ''
            else:
                skipped_junk += 1
                continue
        if not KEEP_NODATA.get(shop, True) and not comp.strip():
            skipped_nodata += 1
            continue
        sostav = extract_sostav(comp)
        if not sostav and shop == 'av' and cat == 'Овощи и фрукты':
            # AV не публикует состав для свежих фруктов/овощей — он совпадает с названием
            sostav = name.split(',')[0].strip().lower()
        if label:
            # этикетка раскрывает суб-ингредиенты (E-добавки внутри кремов, глазурей);
            # добавляем после extract_sostav, т.к. он обрезает по «Пищевая ценность» и т.п.
            sostav = (sostav + '; ' + label).strip('; ')
        low = sostav.lower()
        ings = split_ingredients(sostav)
        natural = (not ings) and cat == 'Овощи и фрукты'
        nodata = not ings and not natural
        adds = find_additives(ings)
        risk_max = max([a['lvl'] for a in adds], default=0) if ings else (0 if natural else -1)
        verdict = 'natural' if natural else ('nodata' if nodata else {0:'safe',1:'safe_min',2:'moderate',3:'high'}[risk_max])
        risk_score = (risk_max*3 + sum(1 for a in adds if a['lvl']>=2)) if ings else 0
        fl = flags_of(low, name.lower())
        if natural: fl = {k: False for k in fl}
        for a in adds:
            a['long'] = LONG_TERM.get(a['name'], CLASS_LT.get(a['cls'], ''))
            adi, fr = ADI_DB.get(a['name'], (None, CLASS_FREQ.get(a['cls'], 'weekly')))
            a['adi'] = adi
            a['freq'] = fr
        price = row.get('price_num')
        if price is None and isinstance(row.get('price'), str):
            m = re.search(r'([\d.,]+)', row['price'])
            price = float(m.group(1).replace(',','.')) if m else None
        img = row.get('image','')
        if shop == 'green':
            # /uploads/{file} отдаёт 404; реальные файлы — на io.activecloud.com с префиксом размера
            m2 = GREEN_IMG_RE.match(img)
            if m2: img = GREEN_IMG_HOST + m2.group(1)
        products.append({'id':len(products),'name':name,'cat':cat,'shop':shop,'price':price,
            'weight':row.get('weight',''),'img':img,'url':row.get('url',''),
            'brand':row.get('brand',''),'sostav':sostav,'verdict':verdict,'verdict_ru':VERDICT_RU[verdict],
            'risk_max':risk_max,'risk_score':risk_score,'adds':adds,'flags':fl,'n_ing':len(ings)})

print('Пищевых товаров:', len(products), '| исключено псевдо-составов:', skipped_junk,
      '| green без состава (ждём допарсинг):', skipped_nodata)
print('по магазинам:', Counter(p['shop'] for p in products))
if green_unmatched:
    print('green: пропущенные рубрики (с составом, не еда):', dict(green_unmatched))
print(Counter(p['verdict'] for p in products))
print('с КПД:', sum(1 for p in products if any(a['name']=='Комплексная пищевая добавка' for a in p['adds'])))
with open('/tmp/products_full.pkl','wb') as f: pickle.dump(products, f)
print('OK')